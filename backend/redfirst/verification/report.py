class ExecutionSummary(BaseModel):
    run_index: int
    exit_code: int | None
    duration_ms: int | None
    main_status: str | None
    timed_out: bool
    oom_killed: bool
    exception_type: str | None = None
    message: str = ""
    output_excerpt: str = ""
    stdout_ref: str | None = None


class AttemptSummary(BaseModel):
    number: int
    status: str
    model: str | None = None
    prompt: str | None = None
    validation_errors: list[str] = Field(default_factory=list)
    validation_warnings: list[str] = Field(default_factory=list)
    strategy: str | None = None
    assumptions: list[str] = Field(default_factory=list)
    test_code: str | None = None
    contract: dict[str, Any] | None = None
    executions: list[ExecutionSummary] = Field(default_factory=list)


class EvidenceReport(BaseModel):
    investigation_id: str
    state: str
    outcome: str | None
    outcome_reason: str | None
    created_at: datetime
    completed_at: datetime | None
    bug_report: dict[str, Any]
    repository: dict[str, Any]
    relevant_files: list[dict[str, Any]]
    attempts: list[AttemptSummary]
    final_test: str | None
    evidence: list[str]
    error: dict[str, Any] | None
    timeline: list[dict[str, Any]]
    limitations: list[str]
    next_steps: list[str]


def build_report(s: Session, inv: Investigation) -> EvidenceReport:
    report = s.get(BugReport, inv.bug_report_id)
    repo = s.get(Repository, inv.repository_id)
    records = s.scalars(select(EvidenceRecord).where(EvidenceRecord.investigation_id == inv.id)
                        .order_by(EvidenceRecord.id)).all()
    events = s.scalars(select(InvestigationEvent)
                       .where(InvestigationEvent.investigation_id == inv.id)
                       .order_by(InvestigationEvent.id)).all()

    attempts: list[AttemptSummary] = []
    for a in inv.attempts:
        meta = a.llm_metadata or {}
        gt = a.generated_test
        val = (gt.validation_result or {}) if gt else {}
        attempts.append(AttemptSummary(
            number=a.number, status=a.status, model=meta.get("model"),
            prompt=f"{meta['prompt_name']}@{meta['prompt_version']}" if meta.get("prompt_name")
            else None,
            validation_errors=val.get("errors", []) or ([meta["error"]] if "error" in meta else []),
            validation_warnings=val.get("warnings", []),
            strategy=val.get("strategy"), assumptions=val.get("assumptions", []),
            test_code=gt.code if gt else None, contract=gt.contract if gt else None,
            executions=[ExecutionSummary(
                run_index=e.run_index, exit_code=e.exit_code, duration_ms=e.duration_ms,
                main_status=e.main_status.value if e.main_status else None,
                timed_out=e.timed_out, oom_killed=e.oom_killed,
                exception_type=(e.parsed or {}).get("exception_type"),
                message=(e.parsed or {}).get("message", "")[:1000],
                output_excerpt=(e.stdout_excerpt or "")[-2000:], stdout_ref=e.stdout_ref,
            ) for e in a.executions],
        ))
    executed = [a for a in attempts if a.executions]
    final_test = executed[-1].test_code if executed else None
    verdicts = [r.payload for r in records if r.kind == "verdict"]
    evidence = verdicts[-1].get("evidence", []) if verdicts else []

    limitations = []
    if report.missing_fields:
        limitations.append("Not provided in the report: " + ", ".join(report.missing_fields) + ".")
    if inv.outcome is Outcome.NOT_REPRODUCED:
        limitations.append("NOT_REPRODUCED means the bug was not observed under the tested "
                           "conditions; it does not prove the bug is absent.")
    for a in executed[-1:]:
        if a.assumptions:
            limitations.append("Model assumptions: " + "; ".join(a.assumptions))
        limitations.extend(a.validation_warnings)
    limitations.append("Tests run offline with only pytest installed; code that needs other "
                       "dependencies or services cannot be exercised.")

    return EvidenceReport(
        investigation_id=inv.id, state=inv.state.value,
        outcome=inv.outcome.value if inv.outcome else None,
        outcome_reason=inv.outcome_reason.value if inv.outcome_reason else None,
        created_at=inv.created_at, completed_at=inv.completed_at,
        bug_report={"title": report.title, "description": report.description,
                    "expected_behavior": report.expected_behavior,
                    "actual_behavior": report.actual_behavior,
                    "missing_fields": report.missing_fields},
        repository={"id": repo.id, "source_type": repo.source_type, "sha256": repo.sha256,
                    "layout": (repo.layout or {}).get("layout")},
        relevant_files=[r.payload for r in records if r.kind == "code_location"],
        attempts=attempts, final_test=final_test, evidence=evidence, error=inv.error,
        timeline=[{"at": e.created_at.isoformat(), "state": e.to_state.value,
                   "message": e.message} for e in events],
        limitations=limitations,
        next_steps=_NEXT_STEPS.get(inv.outcome_reason, ["Inspect the error and logs, then retry."])
        if inv.outcome_reason else [],
    )


def render_markdown(r: EvidenceReport) -> str:
    lines = [
        f"# REDFIRST investigation {r.investigation_id}",
        "",
        f"**Outcome:** {r.outcome or r.state}" + (f" ({r.outcome_reason})" if r.outcome_reason
                                                   else ""),
        "",
        "## Bug report",
        f"- Title: {r.bug_report['title']}",
        f"- Expected: {r.bug_report['expected_behavior'] or '(not provided)'}",
        f"- Actual: {r.bug_report['actual_behavior'] or '(not provided)'}",
        "",
        "## Evidence",
        *[f"- {e}" for e in r.evidence or ["(none recorded)"]],
    ]
    if r.error:
        lines += ["", "## Error", f"- {r.error.get('type')}: {r.error.get('detail')}"]
    files = [f"- `{f['file']}` (score {f['score']}): {'; '.join(f['reasons'])}"
             for f in r.relevant_files]
    lines += ["", "## Relevant files", *(files or ["- (none)"])]
    for a in r.attempts:
        lines += ["", f"## Attempt {a.number}: {a.status}"]
        if a.model:
            lines.append(f"- Model: {a.model}, prompt {a.prompt}")
        lines += [f"- Rejected: {e}" for e in a.validation_errors]
        for e in a.executions:
            lines.append(f"- Run {e.run_index}: {e.main_status} exit={e.exit_code} "
                         f"{e.duration_ms}ms timed_out={e.timed_out} oom={e.oom_killed} "
                         f"{e.exception_type or ''} {e.message[:200]}".rstrip())
    if r.final_test:
        lines += ["", "## Executed test (model-generated)", "```python", r.final_test.rstrip(),
                  "```"]
    lines += ["", "## Limitations", *[f"- {x}" for x in r.limitations],
              "", "## Next steps", *[f"- {x}" for x in r.next_steps or ["(none)"]]]
    return "\n".join(lines) + "\n"
