"""Evidence report: everything a developer needs to check REDFIRST's conclusion.

Built only from persisted records; nothing here is generated by the LLM except the
test code, strategy and assumptions, which are labelled as model output.
"""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from redfirst.db.models import (
    BugReport,
    EvidenceRecord,
    Investigation,
    InvestigationEvent,
    Repository,
)
from redfirst.domain.enums import Outcome, OutcomeReason

